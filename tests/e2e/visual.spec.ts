import { test, expect } from './fixture.js';
test('trusted inspector saves source text once without an AI key or a second acceptance action', async ({ page, workerBridge }) => {
    workerBridge.failNext('visual.selection.open', 'Окно выделения недоступно. Выберите элемент в списке.');
    await page.goto('/');
    await page.getByRole('button', { name: 'Создать сайт', exact: true }).click();
    await page.getByLabel('Домен', { exact: true }).fill('visual.test');
    await page.getByRole('button', { name: 'Создать', exact: true }).click();
    await expect(page.getByText('Локальная версия готова', { exact: true })).toBeVisible({ timeout: 30000 });
    await page.getByRole('button', { name: 'Правки visual.test' }).click();
    await page.getByRole('button', { name: 'Выбрать элемент', exact: true }).click();
    await expect(page.getByLabel('Элемент', { exact: true })).toBeVisible();
    const option = await page.getByLabel('Элемент', { exact: true }).locator('option').allTextContents();
    const index = option.findIndex(t => t.includes('<h1>'));
    expect(index).toBeGreaterThan(0);
    await page.getByLabel('Элемент', { exact: true }).selectOption({ index });
    await page.getByLabel('Текст', { exact: true }).fill('Saved visual title');
    await page.evaluate(() => window.postMessage({ version: 1, sessionId: 'foreign', token: 'wrong', save: true }, '*'));
    expect(workerBridge.requests.filter(r => r.method === 'visual.submit')).toHaveLength(0);
    await page.setViewportSize({ width: 1440, height: 1100 });
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.screenshot({ path: '.local-state/visual-inspector-viewport.png', fullPage: false });
    await page.getByRole('button', { name: 'Сохранить в черновик', exact: true }).click();
    await expect(page.getByText('Черновик сохранён.', { exact: true })).toBeVisible({ timeout: 30000 });
    await expect(page.getByText('Есть принятый черновик', { exact: true })).toBeVisible();
    await expect(page.getByRole('button', { name: 'Принять в черновик' })).toBeDisabled();
    expect(await page.locator('iframe').count()).toBe(0);
    expect(workerBridge.requests.filter(r => r.method === 'visual.submit')).toHaveLength(1);
    expect(workerBridge.requests.filter(r => r.method === 'edit.accept' || r.method === 'site.publish')).toHaveLength(0);
    await page.reload();
    await page.getByRole('button', { name: 'Правки visual.test' }).click();
    await expect(page.getByText('Есть принятый черновик', { exact: true })).toBeVisible();
    await expect(page.getByRole('img', { name: 'После — visual.test' })).toBeVisible();
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.screenshot({ path: '.local-state/visual-editor-viewport.png', fullPage: false });
});
