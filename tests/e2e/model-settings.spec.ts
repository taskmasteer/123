import { test, expect } from './fixture.js';
test('settings clear submitted keys and truthfully distinguish model, local storage and demo publication', async ({ page, workerBridge }) => {
    await page.goto('/');
    await page.getByRole('button', { name: 'Устройство', exact: true }).click();
    await page.getByLabel('API-ключ OpenAI').fill('synthetic-browser-key', { timeout: 5000 });
    await page.getByLabel('Текстовая модель', { exact: true }).fill('configured-text');
    await page.getByRole('button', { name: 'Сохранить и подключить' }).click();
    await expect(page.getByLabel('API-ключ OpenAI')).toHaveValue('');
    await expect(page.getByText('OpenAI · configured-text', { exact: true })).toBeVisible();
    await expect(page.getByText('Изображения отключены', { exact: true })).toBeVisible();
    await expect(page.getByText('Демонстрационная публикация', { exact: true })).toBeVisible();
    await expect(page.getByText('Демо — без внешних сервисов')).not.toBeVisible();
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.screenshot({ path: '.local-state/model-settings-live-harness.png', fullPage: true });
    workerBridge.failNext('model_settings', 'Synthetic OS store unavailable');
    await page.getByLabel('API-ключ OpenAI').fill('synthetic-failed-key');
    await page.getByRole('button', { name: 'Сохранить и подключить' }).click();
    await expect(page.getByLabel('API-ключ OpenAI')).toHaveValue('');
    await expect(page.getByRole('alert').filter({ hasText: 'Synthetic OS store unavailable' })).toBeVisible();
    await page.getByRole('button', { name: 'Удалить ключ' }).click();
    await expect(page.getByText('Модель отключена', { exact: true })).toBeVisible();
    await page.getByRole('button', { name: 'Включить демо' }).click();
    await expect(page.getByText('Демонстрационная модель', { exact: true })).toBeVisible();
    await page.setViewportSize({ width: 1040, height: 680 });
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.screenshot({ path: '.local-state/model-settings-minimum-harness.png', fullPage: true });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    expect(JSON.stringify(workerBridge.requests)).not.toContain('synthetic-browser-key');
});
